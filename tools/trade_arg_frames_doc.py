"""Renderer for docs/arg_frames_pump_pump_amm.md (imported by trade_arg_frames.py).

Every figure is computed from the records the tool just measured, so the page and
the maps stay in step: numbers are interpolated, never typed by hand.
"""
import json

KIND = {'own': 'handler frame', 'helper': 'deserialiser'}


def tname(t):
    if isinstance(t, str):
        return t
    if 'defined' in t:
        return t['defined']['name']
    if 'option' in t:
        return 'Option<%s>' % tname(t['option'])
    if 'vec' in t:
        return 'Vec<%s>' % tname(t['vec'])
    if 'array' in t:
        return '[%s; %d]' % (tname(t['array'][0]), t['array'][1])
    return json.dumps(t)


def frame_col(r):
    out = []
    for f in r['args_expected']:
        if f['off'] is None:
            out.append('%s:%s@?' % (f['name'], tname(f['type'])))
        elif f['size'] is None:
            out.append('%s:%s@%d' % (f['name'], tname(f['type']), f['off']))
        else:
            out.append('%s:%s@%d+%d' % (f['name'], tname(f['type']), f['off'], f['size']))
    return ', '.join(out) or '-'


def gate_col(r):
    if not r['gates']:
        return '-'
    return ', '.join('%s %s@%s' % (g['op'], g['imm'], g['pc']) for g in r['gates'])


def reader_col(r):
    rd = r['reader']
    if rd == 'none':
        return 'not read'
    if rd['kind'] == 'own':
        return 'handler (`r%d`)' % rd['reg']
    base = rd.get('base')
    return '`%s`%s' % (rd['frame'], '' if base is None else ' (base %d)' % base)


def span_col(r):
    return ', '.join('%d+%d' % (s['off'], s['width']) for s in r['spans']) or '-'


def counts(out):
    c = {'own': [], 'helper': [], 'none': []}
    for n, r in out.items():
        rd = r['reader']
        c['none' if rd == 'none' else rd['kind']].append(n)
    full = [n for n, r in out.items() if r['frame_check'].endswith('all declared fields loaded')]
    var = [n for n, r in out.items() if any(f['size'] is None for f in r['args_expected'])]
    adv = [n for n, r in out.items() if r['unplaced_reads']]
    return c, sorted(full), sorted(var), sorted(adv)


def delegated_table(L, out, c):
    frames = {}
    for n in c['helper']:
        r = out[n]['reader']
        frames.setdefault(r['frame'], []).append((n, r))
    L.append('| deserialiser frame | instructions | reader base | handlers |')
    L.append('|---|---:|---:|---|')
    for fr in sorted(frames, key=lambda x: int(x, 16)):
        hs = frames[fr]
        base = hs[0][1].get('base')
        L.append('| `%s` | %d | %s | %s |' % (
            fr, hs[0][1]['insns'], 'not fixed' if base is None else str(base),
            ', '.join('`%s`' % n for n, _ in sorted(hs))))
    L.append('')


def gate_histogram(out):
    h = {}
    for r in out.values():
        for g in r['gates']:
            k = '%s %s' % (g['op'], g['imm'])
            h[k] = h.get(k, 0) + 1
    return sorted(h.items(), key=lambda kv: -kv[1])


def caps_table(L, out):
    caps = {}
    for n, r in out.items():
        for c in r['caps']:
            caps.setdefault(json.dumps(c, sort_keys=True), (c, set()))
            caps[json.dumps(c, sort_keys=True)][1].add(n)
    if not caps:
        return
    L.append('| cap | stride | bytes | gate | element | handlers |')
    L.append('|---:|---:|---:|---|---|---|')
    for k in sorted(caps, key=lambda k: (caps[k][0]['cap'], caps[k][0]['gate_pc'])):
        c, hs = caps[k]
        L.append('| %d | %s | %s | `%s` | %s | %s |' % (
            c['cap'], '-' if not c['stride'] else c['stride'],
            '-' if not c['bytes'] else c['bytes'], c['gate_pc'],
            '-' if not c['stride'] else 'length-prefixed array',
            ', '.join('`%s`' % n for n in sorted(hs))))
    L.append('')


def example(out, name, fields=('handler_pc', 'gates', 'reads', 'spans')):
    r = out[name]
    d = {f: r[f] for f in fields}
    d['reader'] = r['reader']
    d['frame_check'] = r['frame_check']
    return r


def render(allout, allsum):
    L = []
    A = L.append
    pump, amm = allout['pump'], allout['pump_amm']
    cp, fp, vp, ap = counts(pump)
    ca, fa, va, aa = counts(amm)
    sp, sa = allsum['pump'], allsum['pump_amm']

    A('# Instruction-data frames of the deployed `pump` and `pump_amm` programs')
    A('')
    A('Anchor strips the 8-byte instruction discriminator before the handler runs: every handler '
      'works on a reader over the instruction bytes that follow it. This page records, for each of '
      'the %d `pump` and %d `pump_amm` deployed handlers, what the code does with that reader - where '
      'the reader comes from, the length gates the bytes are held to, the byte offset and width of '
      'every load, and the Borsh length prefixes and element caps of the variable-length arguments.'
      % (len(pump), len(amm)))
    A('')
    A('Generated by `tools/trade_arg_frames.py`; the raw records are `maps/pump_arg_frames.json` and '
      '`maps/pump_amm_arg_frames.json`. Every figure is an instruction index in the deployed ELF '
      '(`insn = byte_offset / 8`).')
    A('')
    A('## How a frame is recovered')
    A('')
    A('* **Handler attribution comes from the dispatcher.** `disc = sha256("global:" + name)[:8]` is '
      'carried as a little-endian `lddw` immediate and compared with the register form of `jeq` '
      '(op `0x1d`); the branch reaches a stub, and the stub reaches the body with a call or a jump. '
      'That resolves %d `pump` and %d `pump_amm` handlers from the bytes, matching the IDL one for one.'
      % (len(pump), len(amm)))
    A('* **Two reader regimes.** A handler that reads its own arguments holds the caller frame '
      'pointer in `r5`: the reader pointer is `[r5-0x1000]` and the remaining length `[r5-0xff8]`. A '
      'handler that delegates stashes the pointer in a frame slot and calls the generated '
      'deserialiser with `r2 = fp+S`, i.e. `&mut &[u8]` (pointer at `[r2]`, length at `[r2+8]`).')
    A('* **The delegated frame sees an already advanced reader**, so its offsets are relative to the '
      'position the handler handed over. That base is carried per frame: `create_config` hands the '
      'reader at `16` (after two `u64`s) and `create_pool` at `52` (after the `bool` and one option '
      'tag), and the loads inside those frames are placed at `base + off`.')
    A('* **Length gates** are the `jlt`/`jeq` immediates taken against the remaining length: `jlt N` '
      'when N bytes are taken at once, `jeq 0` when a single byte is read (a non-empty reader '
      'suffices), and `jeq N`/`jne N` when an exactly-N-byte frame selects an optional tail.')
    A('* **A `Pubkey` is not one load.** It arrives as a 32-byte inlined copy spread over seven '
      'loads (`ldxw@0`, `ldxh@+4`, `ldxdw@+6`, `ldxb@+14`, `ldxdw@+15`, `ldxdw@+23`, `ldxb@+31`), so '
      'the spans below are merged from the loads rather than read off one instruction.')
    A('* **Loads after an advance** are reported, not guessed: once a callee has moved the reader '
      'the offset of a later load is run-time, and the record counts those loads separately instead '
      'of placing them.')
    A('')

    A('## `pump`: %d handlers' % len(pump))
    A('')
    A('| handler | handler pc | reader | measured spans | length gates | declared frame (IDL) | frame check |')
    A('|---|---|---|---|---|---|---|')
    for n in sorted(pump):
        r = pump[n]
        A('| `%s` | %s | %s | %s | %s | %s | %s |' % (
            n, r['handler_pc'], reader_col(r), span_col(r), gate_col(r), frame_col(r), r['frame_check']))
    A('')
    A('### Counts')
    A('')
    A('* %d handlers declare no arguments, and their bytes agree: the reader is never loaded.'
      % len(cp['none']))
    A('* %d handlers load the argument bytes in their own frame and %d hand the reader to a '
      'deserialiser frame.' % (len(cp['own']), len(cp['helper'])))
    A('* %d handlers reproduce the declared frame completely - every declared field is loaded at the '
      'offset the IDL implies.' % len(fp))
    A('* %d handlers carry at least one variable-length argument (%s).'
      % (len(vp), ', '.join('`%s`' % n for n in vp)))
    A('* %d handler%s read%s past a reader advance, where offsets are run-time: %s.'
      % (len(ap), '' if len(ap) == 1 else 's', 's' if len(ap) == 1 else '',
         ', '.join('`%s`' % n for n in ap)))
    A('')
    A('### Deserialiser frames')
    A('')
    delegated_table(L, pump, cp)
    A('### The one-byte frame and the option tag')
    A('')
    one = sorted(n for n, r in pump.items() if len(r['args_expected']) == 1 and
                 all(f['size'] == 1 for f in r['args_expected']))
    A('%d handlers take a single one-byte argument (%s) and gate it with `jeq 0`: a one-byte read '
      'only needs a non-empty reader, so there is no `jlt`.'
      % (len(one), ', '.join('`%s`' % n for n in one)))
    A('')
    buy = pump['buy']
    A('`buy` (%s) is the clearest option frame: `jlt 8@%s` for the first `u64`, then '
      '`jne 16@%s` and `jeq 17@%s` select the optional tail, and the four loads land at '
      '`%s` - 16 bytes of amounts plus one tag byte per `OptionBool`, 18 bytes in total.'
      % (buy['handler_pc'], buy['gates'][0]['pc'], buy['gates'][1]['pc'], buy['gates'][2]['pc'],
         ', '.join('%s@%d' % (x['op'], x['off']) for x in buy['reads'])))
    A('')
    A('The same shape repeats across the trade family: `buy_v2`/`buy_v3`/`buy_exact_quote_in_v3` '
      'take 17 bytes (two `u64`s and one tag, `jeq 16`), while `buy`/`buy_exact_sol_in` take 18 (two '
      'tags, `jne 16` then `jeq 17`). The tag byte is loaded, not inferred: `ldxb@16` and '
      '`ldxb@17` are in the record.')
    A('')
    A('### Variable-length arguments')
    A('')
    cr = pump['create']
    A('`create` (%s) declares three `String`s and a `Pubkey`. The `u32` length prefix of the first '
      'string is a 4-byte load at offset 0 and the gate in the shared string reader is `jlt 4@%s`; '
      'the element cap is `jlt 1048576@%s`, i.e. a 1 MiB bound applied to the prefix before the '
      'allocation. After the reader moves, the three strings are consumed by that reader and the '
      '`creator` key is loaded from the advanced reader, so %d loads in the frame are recorded '
      'without a static offset.'
      % (cr['handler_pc'], cr['gates'][0]['pc'], cr['caps'][0]['gate_pc'], len(cr['unplaced_reads'])))
    A('')
    dv = pump['distribute_fee_to_holders']
    A('`distribute_fee_to_holders` (%s) takes a `Vec<u64>`: the measured frame is the 4-byte length '
      'prefix at offset 0 (`%s`), and the elements follow at a run-time offset.'
      % (dv['handler_pc'], span_col(dv)))
    ub = pump['update_buyback_config']
    A('`update_buyback_config` (%s) declares one `%s` and measures 9 bytes: the 1-byte tag plus the '
      '8-byte payload, both placed (`%s`).'
      % (ub['handler_pc'], tname(ub['args_declared'][0]['type']), span_col(ub)))
    A('')
    A('### Pubkey arguments')
    A('')
    aur = pump['update_holder_reward_config']
    A('`update_holder_reward_config` (%s) is `bool` + `Pubkey`: 33 bytes, and the record holds the '
      'seven fragment loads that make up the key (`%s`).'
      % (aur['handler_pc'], ', '.join('%s@%d+%d' % (x['op'], x['off'], x['width']) for x in aur['reads'][1:])))
    A('')
    spx = pump['set_params']
    A('`set_params` (%s) is the deepest frame in the program: 72 bytes of `u64` and `Pubkey` fields '
      'loaded at placed offsets, the `bool` at 72 read through the option reader `%s` (gate `%s`), '
      'and the four remaining fields behind that advance; the record counts %d loads past it.'
      % (spx['handler_pc'], spx['reader']['frame'], gate_col(
          dict(gates=[g for g in spx['gates'] if g['frame'] != 'handler'])),
         len(spx['unplaced_reads'])))
    A('')
    A('### Borsh length prefixes and caps')
    A('')
    caps_table(L, pump)
    cap_handlers = sorted({n for n, r in pump.items() for c in r['caps']})
    A('The only cap in `pump` is the 1 MiB string bound, reached from %s. '
      '`multi_hop_curve_swap` reuses the same reader for its `bytes` argument: `amount_in` is a '
      '`u64` at 0 and the `bytes` prefix follows at 8, both in the same 12-byte measured span '
      '(`%s`).' % (', '.join('`%s`' % n for n in cap_handlers),
                   span_col(pump['multi_hop_curve_swap'])))
    A('')

    A('## `pump_amm`: %d handlers' % len(amm))
    A('')
    A('| handler | handler pc | reader | measured spans | length gates | declared frame (IDL) | frame check |')
    A('|---|---|---|---|---|---|---|')
    for n in sorted(amm):
        r = amm[n]
        A('| `%s` | %s | %s | %s | %s | %s | %s |' % (
            n, r['handler_pc'], reader_col(r), span_col(r), gate_col(r), frame_col(r), r['frame_check']))
    A('')
    A('### Counts')
    A('')
    A('* %d handlers declare no arguments and never load the reader.' % len(ca['none']))
    A('* %d load their arguments in their own frame, %d delegate to a deserialiser frame.'
      % (len(ca['own']), len(ca['helper'])))
    A('* %d reproduce the declared frame completely.' % len(fa))
    A('* %d carry a variable-length argument (%s); %d read past a reader advance (%s).'
      % (len(va), ', '.join('`%s`' % n for n in va), len(aa), ', '.join('`%s`' % n for n in aa)))
    A('')
    A('### Deserialiser frames')
    A('')
    delegated_table(L, amm, ca)
    A('### The 8-pubkey array')
    A('')
    cc = amm['create_config']
    A('`create_config` and `update_fee_config` share `%s`. The handler loads '
      '`lp_fee_basis_points` at 0 and `protocol_fee_basis_points` at 8 in its own frame, then hands '
      'the reader at 16 to the array reader, whose per-element gate is `%s`: the 8 x 32 bytes land '
      'at 16..272, and the measured span is %s. The two trailing fields are read after the array '
      'advances the reader (%d loads in the record).'
      % (cc['reader']['frame'], gate_col(dict(gates=[g for g in cc['gates'] if g['frame'] != 'handler'])),
         span_col(cc), len(cc['unplaced_reads'])))
    A('')
    cp2 = amm['create_pool']
    A('`create_pool` (%s) is the widest frame in either program: `u16` at 0, two `u64`s at 2 and 10, '
      'the `coin_creator` key across 18..50, the `bool` at 50 (`ldxb@50`), the first option tag at 51 '
      '(`ldxb@51`), an 8-byte load at 52 under a 9-byte gate (`jlt 9`), then the reader advanced to '
      '60 where the two trailing `OptionBool`s are read through `%s`. Measured span %s, all declared '
      'fields loaded.' % (cp2['handler_pc'], cp2['reader']['frame'], span_col(cp2)))
    A('')
    A('### The one-byte gates')
    A('')
    amm_one = sorted(n for n, r in amm.items() if len(r['args_expected']) == 1 and
                     all(f['size'] == 1 for f in r['args_expected']))
    A('%d `pump_amm` handlers take a single one-byte `bool` (%s) and gate it with `jeq 0`.'
      % (len(amm_one), ', '.join('`%s`' % n for n in amm_one)))
    A('')
    dis = amm['disable']
    A('`disable` (%s) is five bools, and the gate immediates count them: %s. Each `jeq N` requires '
      'the remaining reader to hold N bytes, so the fifth gate is the 5-byte frame.'
      % (dis['handler_pc'], gate_col(dis)))
    A('')
    A('### Option payloads widen the frame')
    A('')
    acp = amm['admin_cto_pool']
    A('`admin_cto_pool` (%s) measures 42 bytes where the tag-only layout is 34: `Pubkey` 0..32, '
      '`bool` at 32, a tag at 33 and the `OptionU64` payload at 34..42. `create_pool` shows the same '
      'effect at its tail, and `update_buyback_config` in both programs is the minimal case at 9 '
      'bytes (tag + `u64`).' % acp['handler_pc'])
    A('')
    A('### Gates')
    A('')
    A('Same gate vocabulary in both programs. `pump_amm`: %s. `pump`: %s.'
      % (', '.join('`%s` x%d' % (k, v) for k, v in gate_histogram(amm)[:8]),
         ', '.join('`%s` x%d' % (k, v) for k, v in gate_histogram(pump)[:8])))
    A('')

    A('## The two programs side by side')
    A('')
    A('* `pump` has %d own-frame, %d delegated and %d argument-free handlers; `pump_amm` %d, %d and '
      '%d.' % (len(cp['own']), len(cp['helper']), len(cp['none']),
               len(ca['own']), len(ca['helper']), len(ca['none'])))
    A('* Both programs load the reader from the same two places: `[r5-0x1000]`/`[r5-0xff8]` in the '
      'handler frame, `[r2]`/`[r2+8]` in a deserialiser frame. The delegated frames are per '
      'argument-struct, so two handlers that declare the same argument list share one.')
    A('* `pump` is the program with variable-length arguments: three `String`s in `create`, `bytes` '
      'in `multi_hop_curve_swap`, `Vec<u64>` in `distribute_fee_to_holders`, and the 1 MiB string '
      'cap. `pump_amm` arguments are fixed-width or `Option`, so it carries no length prefix at all.')
    A('* `pump` measures %d loads and %d gates; `pump_amm` %d and %d.'
      % (sp['reads'], sp['gates'], sa['reads'], sa['gates']))
    A('')

    A('## Verification')
    A('')
    A('`python3 tools/trade_arg_frames.py --prog pump --verify` re-derives every record from the '
      'deployed ELF (SHA-256 `%s`) and compares it with `maps/pump_arg_frames.json` field by field: '
      '%d/%d handlers reproduce exactly. The same for `--prog pump_amm` against SHA-256 `%s`: '
      '%d/%d.' % (sp.get('elf_sha256', ''), len(pump), len(pump), sa.get('elf_sha256', ''),
                  len(amm), len(amm)))
    A('')
    return '\n'.join(L)
