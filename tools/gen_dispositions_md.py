#!/usr/bin/env python3
"""gen_dispositions_md.py - regenerate docs/HANDLER_DISPOSITIONS.md from measured
body metrics (maps/<prog>_bodies.json) instead of the truncated linear spans.

Replaces the previous generator output, whose per-handler `size 7 insns`,
`syscalls {}` and `has_cpi=False` lines were artifacts (see
docs/analysis/S1b_handler_bodies.md).

Usage: gen_dispositions_md.py EVIDENCE_DIR maps/out.md [--append]
"""
import json
import sys

sys.path.insert(0, __file__.rsplit('/', 1)[0])
from handler_bodies import load  # noqa: E402

PROGS = ['pump', 'pump_amm', 'pump_fees', 'mayhem']
MAPNAME = {'pump': 'pump_handlers_full.json', 'pump_amm': 'amm_handlers_full.json',
           'pump_fees': 'fees_handlers_full.json', 'mayhem': 'mayhem_handlers_full.json'}

HEADER = """# Handler dispositions (structural, address-cited, MEASURED)

Generated by `tools/gen_dispositions_md.py` from `maps/<prog>_bodies.json`, which
is produced by `tools/handler_bodies.py` (recursive-descent CFG from the handler
entry, `.rel.dyn`-resolved syscalls, transitive call graph).

Per handler: dispatcher discriminator/stub/handler pc, real body size, direct
callees, direct syscalls with cited call sites, CPI reachability (single
`sol_invoke_signed_rust` wrapper per program), and transitive reachability of the
transfer-fee helper `@0x12a1c` where the program has one.

Supersedes the previous linear-span output (`func_insns: 3..7`,
`relative_callees: 0`, `syscalls: {}`, `has_cpi: false` for all 139 handlers) —
that was an artifact of syscall call-site relocations being mistaken for function
starts. See `docs/analysis/S1b_handler_bodies.md`.

Not a behavioural MATCH claim — harness verification is separate (Rust/LiteSVM,
toolchain-blocked).
"""


def cpi_wrapper(p):
    for pc, nm in p.call_sym.items():
        if nm == 'sol_invoke_signed_rust':
            return pc if pc in p.entries_set else p.func_start_internal(pc), pc
    return None, None


def main():
    ev = sys.argv[1].rstrip('/')
    out = sys.argv[2]
    with open(out, 'w') as f:
        f.write(HEADER)
        for prog in PROGS:
            elf = '%s/%s/deployed.so' % (ev, prog)
            bodies = json.load(open('maps/%s_bodies.json' % prog))
            hm = json.load(open('maps/%s' % MAPNAME[prog]))
            p = load(elf)
            wrap, wrapsite = cpi_wrapper(p)
            f.write('\n## %s\n\n' % prog)
            f.write('- deployed.so sha256 in `docs/MAP_ALL4.md`; CPI wrapper function '
                    '`%s` (single `sol_invoke_signed_rust` site `%s`)\n' % (
                        hex(wrap) if wrap else 'n/a', hex(wrapsite) if wrapsite else 'n/a'))
            if prog == 'pump':
                f.write('- transfer-fee helper `@0x12a1c`\n')
            for r in sorted(bodies['handlers'], key=lambda x: x['name']):
                meta = hm.get(r['name'], {})
                f.write('\n### %s::%s\n\n' % (prog, r['name']))
                f.write('- disc `%s` cmp `%s` stub `%s` handler `%s`\n' % (
                    meta.get('discriminator'), meta.get('cmp'), meta.get('stub_pc'),
                    r['handler_pc']))
                f.write('- body `%s`: %d insns, %d direct callees, %d call-graph nodes\n' % (
                    r['body_pc'], r['body_insns'], r['direct_callees'], r['callgraph_nodes']))
                direct = ', '.join('`%s`@%s' % (k, ','.join(v[:4]))
                                   for k, v in sorted(r['syscalls'].items())) or 'none'
                f.write('- syscalls (direct): %s\n' % direct)
                f.write('- has_cpi=%s (transitive) has_log=%s\n' % (
                    r['has_cpi'], r['has_log']))
                wr = r['watch_reach'].get('0x12a1c')
                if prog == 'pump':
                    f.write('- transfer-fee helper @0x12a1c: %s\n' % (
                        'REACHED depth %d via %s' % (wr['depth'], ' -> '.join(wr['chain']))
                        if wr else 'not reached'))
                if r['syscalls_transitive']:
                    f.write('- syscalls (transitive): %s\n' % ', '.join(
                        sorted(r['syscalls_transitive'])))
    print('wrote %s' % out)


if __name__ == '__main__':
    main()
